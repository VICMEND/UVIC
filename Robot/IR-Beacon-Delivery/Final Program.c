#pragma config(Sensor, in1,    rightIR,        sensorReflection)
#pragma config(Sensor, in2,    leftIR,         sensorReflection)
#pragma config(Sensor, dgtl2,  leftButton,     sensorTouch)
#pragma config(Sensor, dgtl10, RedLED,         sensorDigitalOut)
#pragma config(Sensor, dgtl11, SONAR,          sensorSONAR_cm)
#pragma config(Sensor, I2C_1,  ,               sensorQuadEncoderOnI2CPort,    , AutoAssign )
#pragma config(Sensor, I2C_2,  ,               sensorQuadEncoderOnI2CPort,    , AutoAssign )
#pragma config(Motor,  port1,           rightMotor,    tmotorVex393_HBridge, PIDControl, driveRight, encoderPort, I2C_2)
#pragma config(Motor,  port2,           motorPayload,  tmotorVex393_MC29, openLoop)
#pragma config(Motor,  port10,          leftMotor,     tmotorVex393_HBridge, PIDControl, reversed, driveLeft, encoderPort, I2C_1)
